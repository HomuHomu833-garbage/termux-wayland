#!/bin/sh
# Regenerates keymap-us.h, the default keymap sent to clients (libxkbcommon-tools, xkb-data).
# Another layout at run time: termux-wayland --keymap <file from xkbcli compile-keymap>.
set -e
cd "$(dirname "$0")"
{
	echo "/* Generated by gen-keymap.sh: xkbcli compile-keymap --layout us --model pc105 */"
	echo "static const char keymap_us[] ="
	xkbcli compile-keymap --layout us --model pc105 | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/^/\t"/' -e 's/$/\\n"/'
	echo ";"
} >keymap-us.h
